const isObj = (v) => v && typeof v === 'object' && !Array.isArray(v)

// يدمج المحفوظ فوق الافتراضي: الكائنات مفتاحًا بمفتاح، والمصفوفات تُستبدل كاملة
export function merge(def, saved) {
  if (!isObj(def) || !isObj(saved)) return saved === undefined ? def : saved
  const out = { ...def }
  for (const k of Object.keys(saved)) out[k] = k in def ? merge(def[k], saved[k]) : saved[k]
  return out
}

export const DAYS_AR = ['الأحد', 'الاثنين', 'الثلاثاء', 'الأربعاء', 'الخميس', 'الجمعة', 'السبت']
export const DAYS_EN = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday']
const DAY_CODES = ['Su', 'Mo', 'Tu', 'We', 'Th', 'Fr', 'Sa']

export const arDigits = (s) => String(s).replace(/\d/g, (d) => '٠١٢٣٤٥٦٧٨٩'[d])

const time12 = (hhmm) => {
  const [h0, m] = (hhmm || '0:0').split(':').map(Number)
  const h = h0 % 12 || 12
  return arDigits(m ? `${h}:${String(m).padStart(2, '0')}` : h) + (h0 < 12 ? 'ص' : 'م')
}

// أيام متتالية → مجموعات [بداية، نهاية]
const runs = (days) => {
  const d = [...new Set(days)].filter((x) => x >= 0 && x <= 6).sort((a, b) => a - b)
  const out = []
  for (const x of d) {
    const last = out[out.length - 1]
    if (last && x === last[1] + 1) last[1] = x
    else out.push([x, x])
  }
  return out
}

// "الأحد – الخميس · ٩ص – ٦م"
export function formatHours({ days = [], from, to } = {}) {
  const r = runs(days)
  if (!r.length) return ''
  const d = r.map(([a, b]) => (a === b ? DAYS_AR[a] : b - a === 1 ? `${DAYS_AR[a]} و${DAYS_AR[b]}` : `${DAYS_AR[a]} – ${DAYS_AR[b]}`)).join('، ')
  return from && to ? `${d} · ${time12(from)} – ${time12(to)}` : d
}

// schema.org openingHours: "Su-Th 09:00-18:00"
export function schemaHours({ days = [], from, to } = {}) {
  const r = runs(days)
  if (!r.length || !from || !to) return undefined
  return `${r.map(([a, b]) => (a === b ? DAY_CODES[a] : `${DAY_CODES[a]}-${DAY_CODES[b]}`)).join(',')} ${from}-${to}`
}


const DAY_CODES = ['Su', 'Mo', 'Tu', 'We', 'Th', 'Fr', 'Sa']
export const arDigits = (e) => String(e).replace(/\d/g, (e) => '٠١٢٣٤٥٦٧٨٩'[e])
const time12 = (e) => {
  let [t, n] = (e || '0:0').split(':').map(Number),
    r = t % 12 || 12
  return arDigits(n ? `${r}:${String(n).padStart(2, '0')}` : r) + (t < 12 ? 'ص' : 'م')
}
// يجمع أيام الأسبوع المتتالية في مجالات [من، إلى]
const runs = (days) => {
  const sorted = [...new Set(days)].filter((d) => d >= 0 && d <= 6).sort((a, b) => a - b)
  const out = []
  for (const d of sorted) {
    const last = out[out.length - 1]
    if (last && d === last[1] + 1) last[1] = d
    else out.push([d, d])
  }
  return out
}
export function formatHours({ days: e = [], from: t, to: n } = {}) {
  let r = runs(e)
  if (!r.length) return ''
  let i = r
    .map(([e, t]) =>
      e === t ? DAYS_AR[e] : t - e === 1 ? `${DAYS_AR[e]} و${DAYS_AR[t]}` : `${DAYS_AR[e]} – ${DAYS_AR[t]}`,
    )
    .join('، ')
  return t && n ? `${i} ${time12(t)} – ${time12(n)}` : i
}
export function schemaHours({ days: e = [], from: t, to: n } = {}) {
  let r = runs(e)
  if (r.length && t && n)
    return `${r.map(([e, t]) => (e === t ? DAY_CODES[e] : `${DAY_CODES[e]}-${DAY_CODES[t]}`)).join(',')} ${t}-${n}`
}
